// scripts/pack/starter/build-starter-pack.mjs
//
// Build of the starter pack 1.1.0 under public/packs/. The chair's bytes and metadata are
// constants here and the grass texture is generated, so no fixture script feeds the shipped
// pack. Run with `pnpm pack:starter`; the output is committed and a test rebuilds it byte for
// byte. Importing this module has no side effects: only running it as the entry point writes
// to disk.

import { createHash } from 'node:crypto'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { encodePng } from '../png-encoder.mjs'
import { generateGrassTile } from './grass-tile.mjs'

const PACK_ID = 'vernacular-starter'
const PACK_VERSION = '1.1.0'
const FORMAT_VERSION = 2
const LICENSE = 'CC-BY-4.0'
const ATTRIBUTION = 'The Vernacular Contributors'
const GENERATOR_PATH = 'scripts/pack/starter/build-starter-pack.mjs'
const BUILD_COMMAND = 'pnpm pack:starter'
const LICENSE_TEXT_URL = new URL('./CC-BY-4.0.txt', import.meta.url)
const OUTPUT_DIRECTORY = fileURLToPath(
  new URL(`../../../public/packs/${PACK_ID}-${PACK_VERSION}/`, import.meta.url),
)

// Every period id of core/registries/periods.ts, written out so plain `node` can run this file.
const PERIOD_IDS = [
  'colonial',
  'early-republic',
  'antebellum',
  'victorian',
  'edwardian',
  'interwar',
  'postwar',
  'contemporary',
  'unknown',
]

const CHAIR_BYTES = new TextEncoder().encode('vernacular starter chair 1.1.0 glb placeholder\n')
const CHAIR = {
  name: 'Example chair',
  kind: 'furniture',
  mediaType: 'model/gltf-binary',
  eras: ['mid-century'],
  styles: ['mid-century-modern'],
  categories: ['seating'],
  dimensions: { width: 500, depth: 520, height: 800 },
}

// A minimal 12-byte WebP header: "RIFF" + a four-byte size + "WEBP". Enough for the
// integrity check, which validates the signature rather than decoding the image.
const THUMBNAIL_BYTES = new Uint8Array([
  0x52, 0x49, 0x46, 0x46, 0x04, 0, 0, 0, 0x57, 0x45, 0x42, 0x50,
])

const GRASS_SIDE_PIXELS = 512
const GRASS_TILE_MM = 2000
const GRASS = {
  name: 'Mown grass',
  kind: 'texture',
  mediaType: 'image/png',
  eras: PERIOD_IDS,
  categories: ['ground-cover'],
}

const CHANGELOG = [
  '# Changelog',
  '',
  '## 1.0.0',
  '',
  '- Initial pack.',
  '',
  '## 1.1.0',
  '',
  '- Replace the placeholder chair with a new chair under CC-BY-4.0. Add a generated mown-grass',
  '  texture.',
  '',
].join('\n')

const NOTICE = [
  ATTRIBUTION,
  '',
  `This pack is generated by ${GENERATOR_PATH}.`,
  `Rebuild it with \`${BUILD_COMMAND}\`.`,
  '',
].join('\n')

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
const encodeText = (text) => new TextEncoder().encode(text)

// Both entry builders rebuild their objects to fix the key order of the written
// manifest; do not simplify them to an object spread.
/**
 * The manifest entry of the chair.
 * @param {string} contentHash
 * @returns {object}
 */
function chairEntry(contentHash) {
  const { name, kind, mediaType, eras, styles, categories, dimensions } = CHAIR
  return {
    contentHash,
    name,
    kind,
    mediaType,
    license: LICENSE,
    attribution: ATTRIBUTION,
    eras,
    styles,
    categories,
    dimensions,
  }
}

/**
 * The manifest entry of the grass texture.
 * @param {string} contentHash
 * @returns {object}
 */
function grassEntry(contentHash) {
  const { name, kind, mediaType, eras, categories } = GRASS
  return {
    contentHash,
    name,
    kind,
    mediaType,
    license: LICENSE,
    attribution: ATTRIBUTION,
    eras,
    categories,
    image: { width: GRASS_SIDE_PIXELS, height: GRASS_SIDE_PIXELS },
    tileSize: { width: GRASS_TILE_MM, height: GRASS_TILE_MM },
    colorSpace: 'srgb',
  }
}

/**
 * The pack manifest, with keys in a fixed order.
 * @param {{ chairHash: string, grassHash: string }} hashes
 * @returns {object}
 */
function manifest({ chairHash, grassHash }) {
  return {
    packId: PACK_ID,
    version: PACK_VERSION,
    formatVersion: FORMAT_VERSION,
    license: LICENSE,
    attribution: ATTRIBUTION,
    eras: [...CHAIR.eras, ...GRASS.eras],
    styles: CHAIR.styles,
    categories: [...CHAIR.categories, ...GRASS.categories],
    assets: [chairEntry(chairHash), grassEntry(grassHash)],
  }
}

/**
 * Every file of the starter pack, by its path relative to the pack directory. No disk write.
 * @returns {Promise<Map<string, Uint8Array>>}
 */
export async function buildStarterPack() {
  const grassBytes = encodePng(generateGrassTile())
  const chairHash = sha256(CHAIR_BYTES)
  const grassHash = sha256(grassBytes)
  const manifestText = `${JSON.stringify(manifest({ chairHash, grassHash }), null, 2)}\n`
  return new Map([
    [`assets/${chairHash}.glb`, CHAIR_BYTES],
    [`assets/${grassHash}.png`, grassBytes],
    [`thumbnails/${chairHash}.webp`, THUMBNAIL_BYTES],
    ['manifest.json', encodeText(manifestText)],
    ['LICENSE', new Uint8Array(await readFile(LICENSE_TEXT_URL))],
    ['NOTICE', encodeText(NOTICE)],
    ['CHANGELOG.md', encodeText(CHANGELOG)],
  ])
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = await buildStarterPack()
  await rm(OUTPUT_DIRECTORY, { recursive: true, force: true })
  for (const [relativePath, bytes] of files) {
    const target = join(OUTPUT_DIRECTORY, relativePath)
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, bytes)
  }
}
